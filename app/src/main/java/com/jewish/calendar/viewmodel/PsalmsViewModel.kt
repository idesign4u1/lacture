data class PsalmEntry(val number: Int, val heTitle: String, val opening: String)

enum class PsalmsTab(val label: String) {
    ALL("כל התהילים"), BOOK1("ספר א"), BOOK2("ספר ב"),
    BOOK3("ספר ג"),   BOOK4("ספר ד"), BOOK5("ספר ה")
}

data class PsalmsUiState(
    val tab: PsalmsTab = PsalmsTab.ALL,
    val selectedPsalm: PsalmEntry? = null,
    val text: String = "",
    val isLoading: Boolean = false,
    val readSet: Set<Int> = emptySet(),
    val fontSize: Int = 22
)

@HiltViewModel
class PsalmsViewModel @Inject constructor(
    private val sefariaRepository: SefariaRepository
) : ViewModel() {

    private val _uiState = MutableStateFlow(PsalmsUiState())
    val uiState: StateFlow<PsalmsUiState> = _uiState.asStateFlow()

    val allPsalms: List<PsalmEntry> = buildPsalmList()

    fun psalmsByTab(tab: PsalmsTab): List<PsalmEntry> = when (tab) {
        PsalmsTab.ALL   -> allPsalms
        PsalmsTab.BOOK1 -> allPsalms.filter { it.number in 1..41 }
        PsalmsTab.BOOK2 -> allPsalms.filter { it.number in 42..72 }
        PsalmsTab.BOOK3 -> allPsalms.filter { it.number in 73..89 }
        PsalmsTab.BOOK4 -> allPsalms.filter { it.number in 90..106 }
        PsalmsTab.BOOK5 -> allPsalms.filter { it.number in 107..150 }
    }

    fun selectTab(tab: PsalmsTab) =
        _uiState.update { it.copy(tab = tab, selectedPsalm = null, text = "") }

    fun selectPsalm(psalm: PsalmEntry) {
        _uiState.update { it.copy(selectedPsalm = psalm, text = "", isLoading = true) }
        viewModelScope.launch {
            sefariaRepository.getTextForRef("Psalms ${psalm.number}")
                .onSuccess { t -> _uiState.update { it.copy(text = t, isLoading = false) } }
                .onFailure { _uiState.update { it.copy(text = "", isLoading = false) } }
        }
    }

    fun markRead(number: Int) =
        _uiState.update { it.copy(readSet = it.readSet + number) }

    fun clearPsalm() = _uiState.update { it.copy(selectedPsalm = null, text = "") }
    fun increaseFontSize() = _uiState.update { it.copy(fontSize = (it.fontSize + 2).coerceAtMost(40)) }
    fun decreaseFontSize() = _uiState.update { it.copy(fontSize = (it.fontSize - 2).coerceAtLeast(14)) }

